package com.vell27w.mall.param;

import com.vell27w.mall.common.PageQuery;

import lombok.Data;
import lombok.EqualsAndHashCode;

/**
 * 商品列表查询入参。
 *
 * 继承 PageQuery 拿到 pageNum / pageSize 和它们的安全保护
 * （pageSize 上限 100、null 兜底、offset 换算），这里只声明商品特有的筛选条件。
 *
 * 【三个条件都可选，组合起来就是列表页的全部能力】
 *   分类 + 关键字 + 排序 + 分页 —— 这就是电商列表页的骨架。
 *   每个条件单独出现、或任意组合都要能工作，所以 SQL 里用动态标签拼。
 */
@Data
@EqualsAndHashCode(callSuper = true)
public class GoodsQueryParam extends PageQuery {

    /**
     * 分类 id。为空表示不限分类。
     *
     * 【只按叶子分类精确匹配，不含子分类】
     * 也就是说传一级分类「数码家电」的 id，是查不到东西的 ——
     * 因为商品都挂在三级叶子上（智能手机、笔记本…）。
     * 想要「查整个数码家电」得由调用方把子树 id 都取出来传进来。
     * 先做最简单、且能完整演示索引的那种；扩展的事等真需要时再说。
     */
    private Long categoryId;

    /**
     * 关键字，按商品名模糊匹配。为空（或空字符串）表示不筛选。
     *
     * ⚠️ 匹配方式是 LIKE '%关键字%'，前面带百分号。
     * 这种写法【用不上索引】，只能全表扫 —— 因为 B+Tree 是按前缀有序的，
     * 不知道前缀就没法定位。这是面试高频题（「为什么 like 不走索引」）。
     * 真要做搜索得换方案（全文索引 / ES），本项目明确不做。
     */
    private String keyword;

    /**
     * 排序方式。【只允许下面三个值，其它一律当作默认】：
     *   null / 不传  -> 按 id 倒序（最新的在前）
     *   "price_asc"  -> 按售价升序
     *   "price_desc" -> 按售价降序
     *
     * ============================================================
     * 【为什么是字符串白名单，而不是让前端直接传字段名？】
     * ============================================================
     * 这是本类最重要的一段，也是面试很可能追问的地方。
     *
     * MySQL 的 ORDER BY 后面【不能用 #{} 占位符】——
     * #{} 最终会被编译成预编译语句的 ? ，而 ? 只能代表「一个值」，
     * 不能代表「一个列名」。所以想动态指定排序列，只能做字符串拼接。
     *
     * 一旦拼接，就是 SQL 注入的入口：
     *      ORDER BY ${sort}          ← ⛔ 千万别这么写
     * 前端只要传 sort = "id; DROP TABLE goods_info--"，拼出来的就是合法 SQL。
     * 而且因为它是排在最后面的语句片段，连注释符都不用就能干活。
     *
     * 【正确的做法】不在 SQL 里拼用户输入，而是在【白名单里选】：
     *   Java 这边只把用户传的原样存着，不做任何判断；
     *   XML 里用 <choose> 按字符串比较，命中哪个就用哪段【写死的】ORDER BY。
     *   没命中就用默认那段。
     *
     * 这样用户输入永远只是「用来做比较的字符串」，一个字都进不了 SQL 语句本身。
     * 好处还有：错误值不会报错、不会让接口 500，而是静默回落到默认排序 ——
     * 对公开接口来说，这比抛异常更合适。
     */
    private String sort;
}
